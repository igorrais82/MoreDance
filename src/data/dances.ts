export type DanceStyle = 'standard' | 'latin';
export type Difficulty = 'beginner' | 'easy' | 'medium';

export type LessonStep = {
  count: string;
  title: string;
  instruction: string;
};

export type Lesson = {
  id: string;
  title: string;
  durationMin: number;
  summary: string;
  tip: string;
  steps: LessonStep[];
  bpm: number;
  counts: string[];
  /** Теоретический урок: только материал, без практики под метроном. */
  theory?: boolean;
  /**
   * Урок держания рамы: вместо практики под метроном открывается таймер,
   * который считает, сколько удалось продержать раму без опускания рук.
   */
  frameHold?: boolean;
  /**
   * Специальный урок-прогон: не новый материал и не «седьмой урок», а
   * проверка под музыку. Не нумеруется и выделяется своим цветом.
   */
  runthrough?: boolean;
  /** Длительность прогона в секундах. */
  durationSec?: number;
  /** Свой цвет карточки и акцентов вместо цвета танца. */
  accent?: string;
};

